<?php

/*
|--------------------------------------------------------------------------
| Betachem E-Commerce
| Logout
|--------------------------------------------------------------------------
*/

if (session_status() === PHP_SESSION_NONE) {
    session_start();
}

/*
|--------------------------------------------------------------------------
| URLs
|--------------------------------------------------------------------------
*/

$officialHomeUrl = '/betachem/betachem.betaoffice.co.za/public_html/';

/*
|--------------------------------------------------------------------------
| Clear Session
|--------------------------------------------------------------------------
*/

$_SESSION = [];

/*
|--------------------------------------------------------------------------
| Destroy Session
|--------------------------------------------------------------------------
*/

if (ini_get('session.use_cookies')) {
    $params = session_get_cookie_params();

    setcookie(
        session_name(),
        '',
        time() - 42000,
        $params['path'],
        $params['domain'],
        $params['secure'],
        $params['httponly']
    );
}

session_destroy();

/*
|--------------------------------------------------------------------------
| Redirect To Official Homepage
|--------------------------------------------------------------------------
*/

header('Location: ' . $officialHomeUrl);
exit;